export function loadStoredData<T>(key: string, seed: T): T {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) {
      localStorage.setItem(key, JSON.stringify(seed));
      return seed;
    }
    return JSON.parse(raw) as T;
  } catch (e) {
    console.error(`Error loading storage key ${key}:`, e);
    return seed;
  }
}

export function saveStoredData<T>(key: string, data: T): void {
  try {
    localStorage.setItem(key, JSON.stringify(data));
  } catch (e) {
    console.error(`Error saving storage key ${key}:`, e);
  }
}

export function logSystemAction(
  action: SystemLog['action'],
  targetType: SystemLog['targetType'],
  targetId: string,
  details: string,
  user: string = 'Cán bộ Kỹ thuật'
): SystemLog {
  const newLog: SystemLog = {
    id: `LOG-${Date.now()}`,
    timestamp: new Date().toISOString(),
    user,
    action,
    targetType,
    targetId,
    details,
  };

  const logs = loadStoredData<SystemLog[]>(STORAGE_KEYS.LOGS, SEED_LOGS);
  const updatedLogs = [newLog, ...logs].slice(0, 500);
  saveStoredData(STORAGE_KEYS.LOGS, updatedLogs);
  return newLog;
}
